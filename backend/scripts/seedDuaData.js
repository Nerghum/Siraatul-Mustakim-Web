async function seed() {
  const uri = process.env.MONGODB_URI || "mongodb://127.0.0.1:27017/siraatul-mustakim";
  console.log("Connecting to", uri);
  await mongoose.connect(uri);

  for (const chapter of chapters) {
    await DuaChapter.findOneAndUpdate(
      { chapterId: chapter.chapterId },
      {
        chapterId: chapter.chapterId,
        title: chapter.title,
        icon: chapter.icon,
        serial: chapter.serial,
      },
      { upsert: true, new: true }
    );

    for (const item of chapter.items) {
      await Dua.findOneAndUpdate(
        { duaId: item.duaId },
        {
          duaId: item.duaId,
          chapterId: chapter.chapterId,
          title: item.title,
          arabic: item.arabic,
          pronunciation: item.pronunciation,
          translation: item.translation,
          tafsir: item.tafsir || "",
          sourceLabel: item.sourceLabel || "",
          sourceLabelBangla: item.sourceLabelBangla || "",
          serial: item.serial,
        },
        { upsert: true, new: true }
      );
    }
  }

  console.log("Successfully seeded Dua data!");
  await mongoose.disconnect();
  process.exit(0);
}

seed().catch((err) => {
  console.error("Seed failed:", err);
  process.exit(1);
});
